import * as z from "zod"
import { freshSystemPromptForPlanner, replanSystemPrompt } from "../prompt/planner.prompt.js"
import { SystemMessage, HumanMessage, AIMessage, createAgent, providerStrategy } from "langchain"
import model, { mistralMedium, nvidiaUltra } from "../model.js"
import { fsTools, listFilesTool, readFilesTool } from "../tools/fs.tool.js"
import { cliTools } from "../tools/cli.tool.js"
import { mainAgentSystemPrompt } from "../prompt/main.prompt.js";
import { testSystemPrompt } from "../prompt/test.prompt.js"
import { streamAgentResponse } from "./stream.js"



/**
 * {
 *  userInput: String,
 *  plannerHistory: Array,
 *  mainHistory: Array,
 *  testHistory: Array,
 *  plan:String,
 *  tasks:[
 *  { 
 *      task: String,
 *      subTasks?: Array
 *   }
 *  ],
 *  mainResults: String,
 *  testResults: String,
 *  testFailedCount: Number,
 *  replannedCount: Number | (max 1)
 * }
 */


export const PlannerNode = async (state, config) => {

    const plannerHistory = state.plannerHistory || []
    const plan = state.plan || ""
    const userInput = state.userInput || ""
    const testResults = state.testResults || ""
    const replannedCount = plan ? (state.replannedCount || 0) + 1 : 0
    const blockers = Array.isArray(state.blockers) ? state.blockers : []


    const outputFormat = z.object({
        plan: z.string().describe("The overall plan generated by the planner"),
        tasks: z.array(z.object({
            name: z.string().describe("Name of the task"),
            subTasks: z.array(z.string()).describe("List of sub-tasks")
        })).describe("List of tasks")
    })

    const agent = createAgent({
        model: nvidiaUltra,
        tools: [ listFilesTool, readFilesTool ],
        responseFormat: providerStrategy(outputFormat)
    })


    const messages = !plan
        ? [
            new SystemMessage(freshSystemPromptForPlanner),
            new HumanMessage(userInput),
        ]
        : [
            ...plannerHistory,
            new HumanMessage(JSON.stringify({
                previousPlan: plan,
                testResults,
                blockers,
            }, null, 2)),
        ]

    const finalResponse = await streamAgentResponse(agent, messages, "planner", config.configurable.emitEvent)

    return {
        plannerHistory: finalResponse.messages,
        plan: finalResponse.structuredResponse.plan,
        tasks: finalResponse.structuredResponse.tasks,
        replannedCount,
        testFailedCount: 0
    }

}

export const MainNode = async (state, config) => {
    const mainHistory = Array.isArray(state.mainHistory) ? state.mainHistory : []
    const tasks = Array.isArray(state.tasks) ? state.tasks : []
    const testerFeedback = state.testResult || state.testResults || ""

    const mainOutputFormat = z.object({
        result: z.string().describe("A concise report of the implementation and verification"),
        verification: z.array(z.string()).describe("Verification commands run and their outcomes"),
        blockers: z.array(z.string()).describe("List of blockers encountered during this run"),
    })

    const agent = createAgent({
        model: nvidiaUltra,
        tools: [ ...fsTools, ...cliTools ],
        responseFormat: providerStrategy(mainOutputFormat),
    })

    const context = {
        userRequest: state.userInput || "",
        plan: state.plan || "",
        tasks,
        previousMainHistory: mainHistory,
        testerFeedback,
        testFailedCount: state.testFailedCount || 0,
    }

    const response = await streamAgentResponse(agent, [
        new SystemMessage(mainAgentSystemPrompt),
        new HumanMessage(JSON.stringify(context, null, 2)),
    ], "main", config.configurable.emitEvent)

    const report = response.structuredResponse

    return {
        mainHistory: [
            ...response?.messages
        ],
        mainResults: report.result,
        blockers: report.blockers,
    }
}

export const TestNode = async (state, config) => {
    const {
        plan,
        userInput,
        mainResults,
        testHistory = [],
        testFailedCount,
        blockers,
    } = state

    const outputFormat = z.object({
        testResults: z.string().describe("The results of the tests run by the Main agent"),
        status: z.boolean().describe("Whether the tests passed or failed")
    })

    const agent = createAgent({
        model,
        tools: [ listFilesTool, readFilesTool, ...cliTools ],
        responseFormat: providerStrategy(outputFormat),
    })

    const testAgentMessages = testHistory.length > 0 ? testHistory : [ new SystemMessage(testSystemPrompt) ]


    const context = new HumanMessage(JSON.stringify({
        plan,
        userInput,
        mainResults,
        blockers
    }))

    const response = await streamAgentResponse(agent, [
        ...testAgentMessages,
        context,
    ], "test", config.configurable.emitEvent)


    return {
        testHistory: response?.messages,
        testResults: response?.structuredResponse?.testResults || "",
        status: response?.structuredResponse?.status || false,
        testFailedCount: response?.structuredResponse?.status === false ? (testFailedCount || 0) + 1 : testFailedCount || 0,
        testStatus: response?.structuredResponse?.status || false
    }
}

